# Writes package\r6\tweaks\zz_ChromeStride\ChromeStride.yaml (Chrome Stride, 2026-10-27).
# Edit the tables below and run: python -I -X utf8 tools/build_yaml.py
# Record names checked against the 2.31 REDmod TweakDB sources
# (<game>\tools\redmod\tweaks\base\gameplay\static_data\database\items\cyberware\legs\legs_advanced.tweak).
#
# 1.3.0, inheritance: TweakXL resolves record inheritance (red4ext\plugins\TweakXL\Data\InheritanceMap.dat, log line
# "Resolving inheritance..." after every YAML is read), so an !append-once on the Uncommon record of an implant also lands
# on the 8 tier records that derive from it (legs_advanced.tweak: every other tier is ": AdvancedBoostedTendonsUncommon"
# with "OnEquip +="). 1.0.0 to 1.2.0 appended a full package to every tier, so every tier 2+ to 5++ implant carried its own
# bonus plus the tier 2 one (a modifier dump in game: 8 x 0.0425 next to 8 x 0.15, the unexplained +34 %). Now the
# Uncommon record carries the tier 2 base, which rightly reaches every tier, and each derived tier an increment (tier value
# minus the base), so the sum per tier is exactly the table value. The carry penalty moved into the script (one place,
# no inheritance question on the carry restrictions).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
# Folder name starts with zz_ so the file loads after r6\tweaks\running_man.yaml and its flats win.
OUT = os.path.join(HERE, '..', 'package', 'r6', 'tweaks', 'zz_ChromeStride', 'ChromeStride.yaml')
VERSION = '1.4.3'

# (record suffix, tier shown in game, sprint bonus in % at 20 points of the attuned attribute)
TIERS = [
    ('Uncommon', '2', 17), ('UncommonPlus', '2+', 22),
    ('Rare', '3', 28), ('RarePlus', '3+', 34),
    ('Epic', '4', 41), ('EpicPlus', '4+', 50),
    ('Legendary', '5', 60), ('LegendaryPlus', '5+', 65), ('LegendaryPlusPlus', '5++', 70),
]
BASE_PCT = TIERS[0][2]   # the tier 2 value sits on the Uncommon record and reaches every tier through inheritance
# (name used in our records, game record family, attuned stat, attribute name in the UI)
IMPLANTS = [
    ('ReinforcedTendons', 'Items.AdvancedBoostedTendons', 'BaseStats.Reflexes', 'Reflexes'),
    ('FortifiedAnkles', 'Items.AdvancedReinforcedMuscles', 'BaseStats.Strength', 'Body'),
]
# MaxSpeed cap in m/s (vanilla 15, Running Man 25). 26 = the top speed measured on wild cheetahs while hunting
# (25.9 m/s, Wilson et al., Nature 2013); pronghorn and springbok reach about 24.6 m/s.
SPEED_CAP = 26.0


def num(x):
    s = ('%.6f' % x).rstrip('0').rstrip('.')
    return s if s else '0'


def half_group(c, k, ref):
    # One half of the bonus: c + k * attribute (AdditiveMultiplier on MaxSpeed, so it adds to Jenkins' and Leeroy's %).
    return [
        '      statGroup:',
        '        $type: StatModifierGroup',
        '        statModsLimit: -1',
        '        statModifiers:',
        '          - $type: ConstantStatModifier',
        '            statType: BaseStats.MaxSpeed',
        '            modifierType: AdditiveMultiplier',
        '            value: ' + num(c),
        '          - $type: CombinedStatModifier',
        '            statType: BaseStats.MaxSpeed',
        '            modifierType: AdditiveMultiplier',
        '            refStat: ' + ref,
        "            opSymbol: '*'",
        '            value: ' + num(k),
    ]


L = [
    '# Chrome Stride %s, 2026-10-29. Generated by tools/build_yaml.py, edit the tables there.' % VERSION,
    '# Sprint speed comes from leg cyberware instead of a global slider (set Walk by Default sprint to 7.5).',
    '# Reinforced Tendons and Fortified Ankles get a sprint-only bonus by tier. Half of it is fixed, half grows',
    '# with the attuned attribute (Reflexes / Body, full at 20). Half of the bonus needs more than 25 % health.',
    "# Jenkins' Tendons, Leeroy Ligament System and Lynx Paws keep their vanilla effects.",
    '# TweakXL resolves record inheritance: the package on the Uncommon (tier 2) record reaches every tier of the implant,',
    '# so the higher tiers only carry the increment above tier 2 (tier value minus %d %%).' % BASE_PCT,
    '# The redscript part (r6\\scripts\\ChromeStride) adds the sprint stamina, the carry penalty, the burst and the build-up.',
    '',
    '# Speed cap: a wild cheetah (25.9 m/s measured while hunting). Running Man sets 25, vanilla 15.',
    'BaseStats.MaxSpeed.max: %.1f' % SPEED_CAP,
    '',
    '# The engine also clamps the player\'s real ground and air speed (player.tweak: maxGroundSpeed 15, maxAirXYSpeed 18;',
    '# the "extended" 30 / 30 only apply while the PSM flag TemporarySpeedLimitIgnore is set, e.g. the Reflexes dash).',
    '# Measured in game: speed stuck at 15.0 m/s with the MaxSpeed stat at 22.7 to 26; with 26 the speed',
    '# followed the stat up to 25.6 (a later test). Raised to the cap.',
    'player.locomotion.maxGroundSpeed: %.1f' % SPEED_CAP,
    'player.locomotion.maxAirXYSpeed: %.1f' % SPEED_CAP,
    '',
    '# Running Man (26611) charges its double sprint 0.4 stamina per frame, which depends on the frame rate. Chrome Stride',
    '# charges the double sprint and the burst per second instead (Mod Settings), so the flat is zeroed here; Running Man\'s',
    '# own rules (its stamina perk, free with a Sandevistan at Reflexes skill 60) are honoured by the script.',
    'player.staminaCosts.doubleSprint: 0.0',
    '',
    '# Health above 25 % (vanilla Perks.IsPlayerInCritHealth is "25 % or less").',
    'ChromeStride.NotBadlyHurt:',
    '  $base: Perks.IsPlayerInCritHealth',
    '  comparisonType: Greater',
    '',
    'ChromeStride.SprintingNotBadlyHurt:',
    '  $type: MultiPrereq',
    '  prereqClassName: gameMultiPrereq',
    '  aggregationType: AND',
    '  nestedPrereqs:',
    '    - Perks.IsPlayerSprinting',
    '    - ChromeStride.NotBadlyHurt',
    '',
]

for name, family, ref, attr in IMPLANTS:
    L.append('# ---- %s (%s*) ----' % (name, family))
    for suffix, tier, pct in TIERS:
        base = suffix == 'Uncommon'
        pkg_pct = pct if base else pct - BASE_PCT
        v = pkg_pct / 100.0
        c, k = v / 4.0, v / 80.0  # per half: at 20 points c + 20k = v/2, two halves = v
        pkg = 'ChromeStride.%s_%s' % (name, 'Base' if base else suffix)
        if base:
            L.append('# Tier %s: +%d %% at 20 %s. Base record: through inheritance this package is on every tier.' % (tier, pct, attr))
            desc = '"+{float_0}%% sprint speed (Chrome Stride), full at 20 %s, half below 25%% health"' % attr
            floats = '[ %d.0 ]' % pct
        else:
            L.append('# Tier %s: +%d %% at 20 %s in total = the base %d %% plus this increment of %d %%' % (tier, pct, attr, BASE_PCT, pkg_pct))
            desc = '"+{float_0}%% more sprint speed at tier %s, +{float_1}%% in total (Chrome Stride)"' % tier
            floats = '[ %d.0, %d.0 ]' % (pkg_pct, pct)
        L += [
            pkg + ':',
            '  $type: GameplayLogicPackage',
            '  effectors:',
            '    - $base: Perks.ApplyStatGroupOnPlayer',
            '      prereqRecord: Perks.IsPlayerSprinting',
        ]
        L += half_group(c, k, ref)
        L += [
            '    - $base: Perks.ApplyStatGroupOnPlayer',
            '      prereqRecord: ChromeStride.SprintingNotBadlyHurt',
        ]
        L += half_group(c, k, ref)
        L += [
            '  UIData:',
            '    $type: GameplayLogicPackageUIData',
            '    localizedDescription: ' + desc,
            '    floatValues: ' + floats,
            '',
            '%s%s:' % (family, suffix),
            '  OnEquip:',
            '    - !append-once ' + pkg,
            '',
        ]

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(L).rstrip('\n') + '\n')
print('wrote', OUT, len(L), 'lines')
